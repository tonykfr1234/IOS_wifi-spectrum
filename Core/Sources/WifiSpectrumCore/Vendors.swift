import Foundation

public enum MacAddress {
    public static func normalize(_ mac: String) -> String { mac.trimmingCharacters(in: .whitespaces).lowercased() }

    /// iOS reports the router's BSSID; randomized or locally administered addresses set bit 1 of the first octet.
    public static func isLocallyAdministered(_ mac: String) -> Bool {
        guard let first = UInt8(mac.prefix(2), radix: 16) else { return false }
        return first & 0x02 != 0
    }

    /// iOS returns BSSIDs without leading zeros ("4:d9:f5:…"); pad each octet to two digits.
    public static func padded(_ mac: String) -> String {
        let parts = mac.split(separator: ":")
        guard parts.count == 6 else { return normalize(mac) }
        return parts.map { $0.count == 1 ? "0" + $0 : String($0) }.joined(separator: ":").lowercased()
    }

    public static func ouiKey(_ mac: String) -> UInt32? {
        let hex = padded(mac).filter(\.isHexDigit)
        guard hex.count >= 6 else { return nil }
        return UInt32(hex.prefix(6), radix: 16)
    }
}

/// IEEE MA-L registry lookup (Resources/oui.tsv, generated by scripts/build_oui.py).
public final class VendorDatabase: @unchecked Sendable {
    private let byOUI: [UInt32: String]

    public var count: Int { byOUI.count }

    public init(entries: [UInt32: String]) { byOUI = entries }

    public convenience init(tsv: String) {
        var map: [UInt32: String] = [:]
        map.reserveCapacity(48_000)
        tsv.enumerateLines { line, _ in
            guard let tab = line.firstIndex(of: "\t"), line.distance(from: line.startIndex, to: tab) == 6,
                  let key = UInt32(line[..<tab], radix: 16) else { return }
            map[key] = String(line[line.index(after: tab)...])
        }
        self.init(entries: map)
    }

    /// Loads the bundled registry; an empty database if the resource is missing.
    public static func bundled() -> VendorDatabase {
        guard let url = Bundle.module.url(forResource: "oui", withExtension: "tsv"),
              let text = try? String(contentsOf: url, encoding: .utf8) else { return VendorDatabase(entries: [:]) }
        return VendorDatabase(tsv: text)
    }

    public func lookup(_ mac: String) -> String? {
        if MacAddress.isLocallyAdministered(MacAddress.padded(mac)) { return nil }
        guard let key = MacAddress.ouiKey(mac) else { return nil }
        return byOUI[key]
    }
}
